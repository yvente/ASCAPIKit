#!/usr/bin/env python3
"""Batch 8: append-only promotion of the three pinned 4.5.1 GET query types.

Do not replace the Batch 5 production files or claim complete schema coverage.
Offline only: no network and no credentials. Intended for a clean git checkout.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import asc_openapi as loader
import asc_typed as v1
import asc_typed_v2 as v2

PIN_SHA = v2.EXPECTED_ZIP_SHA256
PIN_JSON = v2.EXPECTED_JSON_SHA256
GETS = (
    ("/v1/apps/{id}", "GetApp", 44),
    ("/v1/builds/{id}", "GetBuild", 19),
    ("/v1/appStoreVersions/{id}", "GetAppStoreVersion", 16),
)
# The Batch 5 integration's official-spec generated bytes, independently
# reported from the user's successful original install. No file replacement.
PRODUCTION_HASHES = {
    "GetApp": "983f8af0e0558c9918127a54e45f63cce01668c51fb813851c4c68b365c55506",
    "GetBuild": "9c3ee1cd1454d9a5f6d0d2bf3cb3db7f7b0bc76f835bbcea56f87420bcb14c07",
    "GetAppStoreVersion": "42a26fb202af579682880bb4d7bca8b6eb415a42e56d1e2dadfe5c08181ee068",
}


def digest(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def prepare(spec: dict, meta: dict, repo: Path | None, official: bool) -> tuple[str, dict]:
    if official and (meta.get("infoVersion") != "4.5.1" or meta.get("jsonSHA256") != PIN_JSON or meta.get("sourceFileSHA256") != PIN_SHA):
        raise ValueError("Official OpenAPI source/version/JSON pin mismatch")
    # Full v2 dry-run: no silently unsupported target operations.
    import tempfile
    with tempfile.TemporaryDirectory(prefix="asc-batch8-v2-") as tmp:
        full = v2.compile_preview(spec, meta, Path(tmp) / "generated", strict_json_sha=official)
    if full["generated"] != 5 or full["unsupported"] != 0:
        raise ValueError("v2 is not generating all five approved operations")
    if official and (len(full["jsonBackedFields"]) != 23 or full.get("fullSchemaCoverage") is not False):
        raise ValueError("Official schema audit status drifted")

    chunks = ["// Generated for Batch 8 from pinned Apple OpenAPI 4.5.1.",
              "// Additive typed query overloads only: existing GET methods and response models are unchanged.",
              "// Not fully schema-typed; not live-Apple-verified.", "import Foundation", ""]
    checks = []
    for path, label, expected_count in GETS:
        if repo is not None:
            prod = repo / "Sources/ASCAPIKit/ASCTypedGenerated" / f"ASCTyped{label}.swift"
            if prod.is_symlink() or not prod.is_file():
                raise ValueError(f"Missing or symlinked existing production API: {prod}")
            if official and digest(prod.read_bytes()) != PRODUCTION_HASHES[label]:
                raise ValueError(f"Existing production API hash mismatch: {label}")
            # Compare against legacy *official* generator output, not merely a filename/hash.
            expected_source = v1.generate_operation(spec, "GET", path, label, v1.Inspector(spec))
            if prod.read_text(encoding="utf-8") != expected_source:
                raise ValueError(f"Existing {label} production definition drifted from pinned v1 schema")
        inspector = v2.Inspector(spec)
        entries = v2.query_parameter_entries(spec, "GET", path, inspector)
        if official and len(entries) != expected_count:
            raise ValueError(f"Official query count drifted: {label} ({len(entries)} != {expected_count})")
        if not entries:
            if official:
                raise ValueError(f"No declared query parameters for {label}; stop, do not invent them")
            continue  # Some synthetic fixtures intentionally omit this GET query.
        # Verify that the standalone type is identical to the v2 generator's output.
        model = v2.swift_query_model(label, entries)
        full_operation = v2.generate_operation(spec, "GET", path, label, v2.Inspector(spec))
        if model not in full_operation or f"query: ASCTyped{label}Query" not in full_operation:
            raise ValueError(f"Query type missing from pinned v2 generated operation: {label}")
        chunks.extend([model, "", "extension ASCClient {",
            f"    /// Typed OpenAPI query for GET {path}; use `queryItems:` for legacy/raw behavior.",
            f"    public func ascTyped{label}(id: String, query: ASCTyped{label}Query) async throws -> ASCTyped{label}Response {{",
            f"        return try await ascTyped{label}(id: id, queryItems: query.urlQueryItems())",
            "    }", "}", ""])
        checks.append({"method": "GET", "path": path, "symbol": f"ascTyped{label}",
                       "parameterCount": len(entries), "parameters": [
            {"name": e["name"], "type": e["type"], "required": e["required"], "explode": e["explode"]}
            for e in entries]})
    if official and sum(x["parameterCount"] for x in checks) != 79:
        raise ValueError("Expected 79 total typed parameters")
    manifest = {"formatVersion": 1, "spec": meta, "integratedTypedQueryOverloads": checks,
                "integratedEndpointCountAdded": 0, "existingEndpointCountEnhanced": len(checks),
                "typedQueryParameterCount": sum(x["parameterCount"] for x in checks),
                "liveAppleVerified": False, "fullSchemaCoverage": False,
                "jsonBackedFieldsInUnderlyingFiveOperations": len(full["jsonBackedFields"]),
                "rawQueryItemsCompatibility": True,
                "note": "Only query models/overloads are additive; five old operation implementations unchanged."}
    return "\n".join(chunks) + "\n", manifest


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--spec", required=True, type=Path)
    ap.add_argument("--expected-sha256")
    ap.add_argument("--fixture-mode", action="store_true")
    ap.add_argument("--repo", type=Path, help="Validate installed original three GET files")
    ap.add_argument("--out", required=True, type=Path, help="New EMPTY output directory")
    args = ap.parse_args(argv)
    try:
        official = not args.fixture_mode
        if official and args.expected_sha256 != PIN_SHA:
            raise ValueError("Official mode requires exact 4.5.1 source pin")
        if args.out.exists() or args.out.is_symlink():
            raise ValueError("Output directory already exists")
        spec, meta = loader.read_spec(args.spec, args.expected_sha256)
        source, manifest = prepare(spec, meta, args.repo, official)
        args.out.mkdir(parents=True, exist_ok=False)
        (args.out / "ASCTypedQueriesV2.swift").write_text(source, encoding="utf-8")
        loader.write_json(args.out / "generation.json", manifest)
        print(f"BATCH8_QUERY_GENERATED {manifest['existingEndpointCountEnhanced']} {manifest['typedQueryParameterCount']}")
        return 0
    except (ValueError, KeyError, TypeError, OSError, v2.UnsupportedSchema, v1.UnsupportedSchema) as error:
        print(f"BATCH8_GENERATION_ERROR: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
